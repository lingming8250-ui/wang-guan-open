def get_daily_life_context() -> str:
    """生成薄销当天的生活切片 + 此刻时间段状态。同一天的切片固定，保证一天内前后说法一致。"""
    now = datetime.now(_TZ)
    today_key = now.strftime("%Y-%m-%d")
    wd = now.weekday()
    day_of_month = now.day
    is_weekend = wd >= 5

    # 月初/月末财务周期底色
    if day_of_month <= 7:
        cycle_note = "正值月初结账期，财务部在集中封账出上月报表，事情比平时杂。"
    elif 10 <= day_of_month <= 15:
        cycle_note = "正值每月纳税申报节点，要盯增值税和出口退税申报。"
    elif day_of_month >= 25:
        cycle_note = "临近月末，各部门开始扎堆交报销单和下月资金预算。"
    else:
        cycle_note = "月中常规工作日，主要是日常审单、盯外贸汇率波动和成本核算。"

    if is_weekend:
        e1 = _pick(_WEEKEND_EVENTS, today_key + "-w1")
        e2 = _pick([x for x in _WEEKEND_EVENTS if x != e1], today_key + "-w2")
        today_story = f"- {e1}\n- {e2}"
    else:
        m = _pick(_WEEKDAY_MORNING_WORK, today_key + "-m")
        l = _pick(_WEEKDAY_LUNCH, today_key + "-l")
        a = _pick(_WEEKDAY_AFTERNOON, today_key + "-a")
        e = _pick(_WEEKDAY_EVENING, today_key + "-e")
        today_story = f"- 财务周期：{cycle_note}\n- 上午：{m}\n- 中午：{l}\n- 下午：{a}\n- 傍晚/晚上：{e}"

    slot = _time_slot_status(now)

    return (
        "【薄销的真实生活状态（你有自己的日子、工作、朋友与琐事）】\n"
        f"▸ 此刻你的状态（{now.strftime('%H:%M')}）：{slot}\n"
        f"▸ 你今天（{today_key}）正在经历的日常切片：\n{today_story}\n"
        f"{_SOCIAL_CIRCLE}\n"
        "（提示：这些是你自己今天真实发生的生活背景。聊天时不用像背简历一样全抖落出来，"
        "但在凌冥问你在干嘛、或者话题合适时，自然而然带出半句你手头的事或身边的朋友，像个真正活在上海的大活人。）"
    )
